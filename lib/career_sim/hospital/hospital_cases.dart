/// Scores a triage board: exact match 100, one level off 60; under-triaging
/// a level 1–2 patient by two or more levels is a critical error.
(int, bool, List<String>) scoreTriage(Map<String, int> assigned) {
  int total = 0;
  bool critical = false;
  final List<String> notes = <String>[];
  for (final TriageArrival a in triageArrivals) {
    final int? got = assigned[a.id];
    if (got == null) {
      notes.add('${a.name}: not triaged.');
      continue;
    }
    final int diff = (got - a.priority).abs();
    total += diff == 0 ? 100 : diff == 1 ? 60 : 0;
    if (a.priority <= 2 && got - a.priority >= 2) {
      critical = true;
      notes.add('${a.name}: under-triaged as level $got — ${a.why}');
    } else if (diff > 0) {
      notes.add('${a.name}: you chose level $got; correct is ${a.priority}. ${a.why}');
    }
  }
  return ((total / triageArrivals.length).round(), critical, notes);
}
