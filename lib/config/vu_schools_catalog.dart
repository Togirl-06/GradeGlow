/// Grade Glow Virtual University — schools and programs directory.
///
/// Every program has a [roadmapSubjectId] and opens a live roadmap
/// (rich faculty catalog when mapped, otherwise a full course/topic tree).
class VuSchoolProgram {
  const VuSchoolProgram({
    required this.id,
    required this.title,
    required this.roadmapSubjectId,
    this.blurb,
    this.courses = const <String>[],
  });

  final String id;
  final String title;

  /// Subject id for [VuV2RoadmapSync.forSubjectId].
  final String roadmapSubjectId;
  final String? blurb;

  /// Course titles used when this program has no external rich catalog.
  final List<String> courses;
}

class VuSchool {
  const VuSchool({
    required this.id,
    required this.title,
    required this.emoji,
    required this.programs,
    this.blurb,
  });

  final String id;
  final String title;
  final String emoji;
  final String? blurb;
  final List<VuSchoolProgram> programs;
}

