  static VuSchool? byId(String id) {
    for (final VuSchool s in schools) {
      if (s.id == id) return s;
    }
    return null;
  }

  static VuSchoolProgram? programById(String id) {
    for (final VuSchool s in schools) {
      for (final VuSchoolProgram p in s.programs) {
        if (p.id == id || p.roadmapSubjectId == id) return p;
      }
    }
    return null;
  }

  /// Prefer exact program id match (roadmapSubjectId may be shared).
  static VuSchoolProgram? programByExactId(String id) {
    for (final VuSchool s in schools) {
      for (final VuSchoolProgram p in s.programs) {
        if (p.id == id) return p;
      }
    }
    return null;
  }

  static VuSchool? schoolForProgramId(String programId) {
    for (final VuSchool s in schools) {
      for (final VuSchoolProgram p in s.programs) {
        if (p.id == programId || p.roadmapSubjectId == programId) return s;
      }
    }
    return null;
  }

