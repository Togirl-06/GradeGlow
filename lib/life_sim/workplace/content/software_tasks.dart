const String _se = 'software_engineer';

WorkScenario _bug({
  required String id,
  required String title,
  required String brief,
  required String code,
  required List<String> lines,
  required int buggyLine,
  required String lineExplain,
  required List<String> fixes,
  required int fix,
  required String fixExplain,
  int minRank = 0,
  int maxRank = 3,
  int difficulty = 1,
}) {
  return WorkScenario(
    id: id,
    careerId: _se,
    title: title,
    brief: brief,
    assignedBy: 'Dev (Tech Lead)',
    station: 'desk',
    minRank: minRank,
    maxRank: maxRank,
    minutes: 75,
    difficulty: difficulty,
    skillGain: const <String, double>{'programming': 3.0, 'problem_solving': 1.0},
    stages: <WorkStage>[
      WorkStage.choice(
        id: '$id-line',
        prompt: 'Which line contains the bug?',
        options: lines,
        correct: buggyLine,
        explanation: lineExplain,
        code: code,
        weight: 1,
      ),
      WorkStage.choice(
        id: '$id-fix',
        prompt: 'What is the best fix?',
        options: fixes,
        correct: fix,
        explanation: fixExplain,
        code: code,
        weight: 1.5,
      ),
    ],
  );
}

