  static List<BusinessCourse> _withCapstone(List<BusinessCourse> courses) =>
      <BusinessCourse>[
        ...courses,
        ..._capstone.map(
          (BusinessCourse c) => BusinessCourse(
            id: '${c.id}_${courses.first.id.split('_').first}',
            code: c.code,
            title: c.title,
            year: c.year,
            emoji: c.emoji,
            lessons: c.lessons
                .map(
                  (BusinessLesson l) => BusinessLesson(
                    id: '${courses.first.id.split('_').first}_${l.id}',
                    title: l.title,
                    outcomes: l.outcomes,
                  ),
                )
                .toList(),
          ),
        ),
      ];

