import '../models/business_school.dart';

/// Virtual University Business School curriculum.
///
/// Flat course lists with no academic-level categories. Every lesson supports
/// Lecture, Video, Textbook Notes, Homework, and Exam.
abstract final class BusinessSchoolCatalog {
  static List<BusinessCourse> coursesFor(BusinessMajor major) =>
      switch (major) {
        BusinessMajor.economics => _economics,
        BusinessMajor.finance => _finance,
        BusinessMajor.marketing => _marketing,
        BusinessMajor.accounting => _accounting,
        BusinessMajor.businessAdministration => _businessAdministration,
      };

  static List<BusinessLessonPath> pathsFor(BusinessMajor major) =>
      coursesFor(major)
      .expand(
        (BusinessCourse course) => course.lessons.map(
          (BusinessLesson lesson) => BusinessLessonPath(
            major: major,
            course: course,
            lesson: lesson,
          ),
        ),
      )
      .toList();

  static BusinessLessonPath defaultPath(BusinessMajor major) =>
      pathsFor(major).first;

  static List<BusinessLessonPath> search(BusinessMajor major, String query) {
    final String q = query.trim().toLowerCase();
    if (q.isEmpty) return const <BusinessLessonPath>[];
    return pathsFor(major)
        .where(
          (BusinessLessonPath path) =>
              path.course.title.toLowerCase().contains(q) ||
              path.lesson.title.toLowerCase().contains(q) ||
              path.lesson.outcomes.any(
                (String o) => o.toLowerCase().contains(q),
              ),
        )
        .toList();
  }

  static BusinessCourse _course({
    required String id,
    required String code,
    required String title,
    required String emoji,
    required List<String> topics,
  }) {
    return BusinessCourse(
      id: id,
      code: code,
      title: title,
      year: 1,
      emoji: emoji,
      lessons: <BusinessLesson>[
        for (var i = 0; i < topics.length; i++)
          BusinessLesson(
            id: '${id}_$i',
            title: topics[i],
            outcomes: <String>[
              'Explain the core ideas, vocabulary, and debates in ${topics[i]}',
              'Apply ${topics[i]} methods to a realistic professional decision',
              'Evaluate evidence, assumptions, limitations, and ethical implications',
              'Communicate a defensible recommendation with clear next steps',
            ],
          ),
      ],
    );
  }

