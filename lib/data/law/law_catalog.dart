  static List<LawSpecialization> get specializations => _buildSpecs();

  static LawSpecialization? byId(String id) {
    for (final LawSpecialization s in specializations) {
      if (s.id == id) return s;
    }
    return null;
  }

  static LawCourse? courseById({required String specId, required String courseId}) {
    final LawSpecialization? s = byId(specId);
    if (s == null) return null;
    for (final LawCourse c in s.courses) {
      if (c.id == courseId) return c;
    }
    return null;
  }

  static LawLesson? lessonById({
    required String specId,
    required String courseId,
    required String lessonId,
  }) {
    final LawCourse? c = courseById(specId: specId, courseId: courseId);
    if (c == null) return null;
    for (final LawLesson l in c.lessons) {
      if (l.id == lessonId) return l;
    }
    return null;
  }

  static int get specializationCount => specializations.length;

  static int get lessonCount => specializations.fold<int>(
        0,
        (int sum, LawSpecialization s) =>
            sum + s.courses.fold<int>(0, (int a, LawCourse c) => a + c.lessons.length),
      );

  static LawLesson get featuredHook {
    final List<LawSpecialization> specs = specializations;
    return specs.first.courses.first.lessons.first;
  }

  /// Compact lesson factory — every track gets a full practice-ready lesson.
  static LawLesson _intro({
    required String id,
    required String title,
    required String field,
    required String hook,
    required String question,
    required String doctrine,
    required List<String> elements,
    String writingType = 'Client memo',
    String? simulationCaseId,
    int objectionIndex = 0,
  }) {
    return LawLesson(
      id: id,
      title: title,
      hook: hook,
      question: question,
      doctrine: doctrine,
      elements: elements,
      briefCaseName: 'Teaching brief: $title ($field)',
      briefFacts: hook,
      briefIssue: question,
      briefRule: doctrine,
      briefHolding:
          'Apply the elements to the hook facts; identify the strongest and weakest element for each side.',
      writingPrompt:
          'Write a short $writingType on this $field dispute. Address each element and one counterargument.',
      writingType: writingType,
      objectionStem:
          'Opposing counsel asks a witness a compound, suggestive question about the key $field fact: '
          '"You agree the other side is clearly wrong here, right?"',
      objectionOptions: const <String>['Leading', 'Hearsay', 'Relevance', 'Asked and answered'],
      correctObjectionIndex: objectionIndex,
      objectionExplain:
          'Leading questions suggest the answer and are generally improper on direct of a friendly witness. '
          'In $field practice, control the record with precise objections.',
      clientOpening: 'I need a $field lawyer. Here is what happened: $hook',
      clientFacts: <String>[
        'Client has documents and a timeline.',
        'Opposing party already made a low settlement offer.',
        'Key witness may be biased.',
        'Deadline or statute of limitations may be approaching.',
      ],
      negotiationOffer:
          'Other side offers a modest settlement and a broad release. Advise accept, counter, or litigate for this $field matter.',
      examHypo:
          '$hook Discuss the governing $field issues using IRAC. Cover: ${elements.join('; ')}.',
      simulationCaseId: simulationCaseId,
    );
  }

  static LawSpecialization _track({
    required String id,
    required String name,
    required String tagline,
    required IconData icon,
    required String courseId,
    required String courseTitle,
    required String courseBlurb,
    required List<LawLesson> lessons,
  }) {
    final List<LawLesson> merged = <LawLesson>[];
    final Set<String> seen = <String>{};
    void addAll(Iterable<LawLesson> batch) {
      for (final LawLesson lesson in batch) {
        if (seen.add(lesson.id)) merged.add(lesson);
      }
    }

    addAll(lessons);
    addAll(LawTopicExtras.forSpec(id));
    addAll(LawTopicMore.forSpec(id));
    addAll(LawTopicCore.forSpec(id));
    addAll(LawTopicWorld.forSpec(id));

    return LawSpecialization(
      id: id,
      name: name,
      tagline: tagline,
      icon: icon,
      courses: <LawCourse>[
        LawCourse(id: courseId, title: courseTitle, blurb: courseBlurb, lessons: merged),
      ],
    );
  }

