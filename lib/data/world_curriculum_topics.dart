/// Exhaustive university-level course and topic titles for Virtual University.
///
/// Use [coursesFor] / [topicsFor] so every faculty can show world-scale coverage.
abstract final class WorldCurriculumTopics {
  /// All course names for a subject id.
  static List<String> coursesFor(String subjectId) {
    return List<String>.from(
      coursesBySubject[subjectId] ?? const <String>[],
      growable: false,
    );
  }

  /// Topic titles for [subjectId] + [courseName] (12–20+ real titles when mapped).
  static List<String> topicsFor({
    required String subjectId,
    required String courseName,
  }) {
    final String key = '$subjectId|${slug(courseName)}';
    final List<String>? exact = _topics[key];
    if (exact != null && exact.isNotEmpty) return List<String>.from(exact);

    // Fuzzy: any key ending with same course slug under this subject.
    final String suffix = '|${slug(courseName)}';
    for (final MapEntry<String, List<String>> e in _topics.entries) {
      if (e.key.startsWith('$subjectId|') && e.key.endsWith(suffix)) {
        return List<String>.from(e.value);
      }
    }

    return _generatedTopics(courseName);
  }

  static String slug(String name) => name
      .toLowerCase()
      .replaceAll(RegExp(r'[^a-z0-9]+'), '_')
      .replaceAll(RegExp(r'^_|_$'), '');

