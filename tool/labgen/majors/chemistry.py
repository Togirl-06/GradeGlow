def titration(key, title, brief, acid_mol, acid_ml, base_c, true_v, calc_name, calc_label, calc_formula, calc_unit, given_v, interp=None):
    x = f'({acid_mol} - {base_c}*v/1000)/(({acid_ml} + v)/1000)'
    return D(key, title, brief,
             [I('v', 'Burette reading (titrant added)', 0, 50, 0.01, 0, 'mL')],
             [O('x', 'Net acid concentration', x, 'mol/L', 6), O('P', 'pH', '-log((x + sqrt(x^2 + 0.00000000000004))/2)', '', 2),
              O(calc_name, calc_label, calc_formula, calc_unit, 5)],
             {'v': given_v}, ['P', calc_name],
             ([ge('P', 4, 'End point reached (pH between 4 and 10)'), le('P', 10, 'End point reached (pH between 4 and 10)')],
              [ge('P', 5, 'Stop within pH 5–9 (indicator colour change)'), le('P', 9, 'Stop within pH 5–9 (indicator colour change)')],
              [ge('v', round(true_v - 0.05, 2), 'Titre within ±0.05 mL of the true end point'), le('v', round(true_v + 0.05, 2), 'Titre within ±0.05 mL of the true end point')]),
             {'v': true_v}, ['[H⁺] = (x + √(x² + 4K_w))/2 where x is the net acid concentration; K_w = 10⁻¹⁴.'], interpret=interp)

