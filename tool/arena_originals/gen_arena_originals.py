#!/usr/bin/env python3
"""Generate lib/data/arena_original_problems.dart from problems.py.

Expected outputs are computed by running each problem's Python reference, so
no expected value is typed by hand. Also writes
functions/test/fixtures/arena_originals.json, which the judge tests use to run
both the Python and JavaScript references through the real harness.

Usage: python3 tool/arena_originals/gen_arena_originals.py
"""
import copy
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
from problems import PROBLEMS  # noqa: E402


def lit(v):
    return json.dumps(v, separators=(',', ':'))


def args_text(params, values):
    return ', '.join(f'{p} = {lit(v)}' for p, v in zip(params, values))


def dart_str(s):
    s = s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n')
    return f"'{s}'"


def starters(p):
    m = re.search(r'def ' + p['fn'] + r'\(self, ([^)]*)\)( -> [^:]+)?:', p['py_src'])
    py_sig = m.group(1) if m else ', '.join(p['params'])
    ret = m.group(2) or '' if m else ''
    py = f"class Solution:\n    def {p['fn']}(self, {py_sig}){ret}:\n        pass\n"
    js = f"/**\n * Write your solution here.\n */\nvar {p['fn']} = function({', '.join(p['params'])}) {{\n    \n}};\n"
    return {'python3': py, 'javascript': js}


def main():
    out_problems = []
    seen = set()
    for p in PROBLEMS:
        assert p['id'] not in seen, p['id']
        seen.add(p['id'])
        def run(values):
            return p['py'](*copy.deepcopy(values))
        examples = []
        for values, why in p['examples']:
            examples.append({'input': args_text(p['params'], values), 'output': lit(run(values)), 'explanation': why})
        hidden = [{'input': args_text(p['params'], v), 'output': lit(run(v))} for v in p['hidden']]
        out_problems.append({
            'id': p['id'], 'title': p['title'], 'slug': p['slug'], 'difficulty': p['difficulty'], 'tags': p['tags'],
            'functionName': p['fn'], 'description': p['description'], 'constraints': p['constraints'],
            'examples': examples, 'hiddenTests': hidden, 'starterCode': starters(p),
            'py_src': p['py_src'], 'js_src': p['js_src'],
        })

    lines = [
        '// GENERATED by tool/arena_originals/gen_arena_originals.py — do not edit by hand.',
        '// Expected outputs come from running each reference solution.',
        "import '../models/leetcode_problem.dart';",
        '',
        '/// GradeGlow-original Algorithm Arena problems with real samples and hidden tests.',
        'abstract final class ArenaOriginalProblems {',
        '  static const List<LeetcodeProblem> all = <LeetcodeProblem>[',
    ]
    for q in out_problems:
        lines.append('    LeetcodeProblem(')
        lines.append(f"      id: {dart_str(q['id'])},")
        lines.append(f"      title: {dart_str(q['title'])},")
        lines.append(f"      slug: {dart_str(q['slug'])},")
        lines.append(f"      difficulty: {dart_str(q['difficulty'])},")
        lines.append(f"      tags: <String>[{', '.join(dart_str(t) for t in q['tags'])}],")
        lines.append(f"      functionName: {dart_str(q['functionName'])},")
        lines.append(f"      description: {dart_str(q['description'])},")
        lines.append('      examples: <LeetcodeExample>[')
        for e in q['examples']:
            exp = f", explanation: {dart_str(e['explanation'])}" if e['explanation'] else ''
            lines.append(f"        LeetcodeExample(input: {dart_str(e['input'])}, output: {dart_str(e['output'])}{exp}),")
        lines.append('      ],')
        lines.append(f"      constraints: <String>[{', '.join(dart_str(c) for c in q['constraints'])}],")
        lines.append('      starterCode: <String, String>{')
        for k, v in q['starterCode'].items():
            lines.append(f"        {dart_str(k)}: {dart_str(v)},")
        lines.append('      },')
        lines.append('      hiddenTests: <LeetcodeHiddenTest>[')
        for h in q['hiddenTests']:
            lines.append(f"        LeetcodeHiddenTest(input: {dart_str(h['input'])}, output: {dart_str(h['output'])}),")
        lines.append('      ],')
        lines.append('    ),')
    lines += ['  ];', '}', '']
    with open(os.path.join(ROOT, 'lib/data/arena_original_problems.dart'), 'w') as f:
        f.write('\n'.join(lines))

    fx = os.path.join(ROOT, 'functions/test/fixtures')
    os.makedirs(fx, exist_ok=True)
    with open(os.path.join(fx, 'arena_originals.json'), 'w') as f:
        json.dump([{k: q[k] for k in ('id', 'title', 'difficulty', 'tags', 'functionName', 'description', 'examples', 'hiddenTests', 'starterCode', 'py_src', 'js_src')} for q in out_problems], f, indent=1)
    print(f'{len(out_problems)} problems written')


if __name__ == '__main__':
    main()
