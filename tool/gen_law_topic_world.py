def dart_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "\\'")


def elements_list(els: str) -> str:
    parts = [p.strip() for p in els.split(";") if p.strip()]
    return ", ".join(f"'{dart_escape(p)}'" for p in parts)


def lesson_call(spec: str, field: str, case_id: str, item: tuple[str, str, str, str], idx: int) -> str:
    sid, title, hook, els = item
    lid = f"world_{spec}_{sid}"
    els_code = elements_list(els)
    ques = f"What issues control, and how do the elements apply?"
    doctrine = (
        f"Apply governing {field} doctrine to the facts; isolate the contested elements, "
        f"burden, and strongest counterargument."
    )
    return (
        f"    LawTopicFactory.intro(\n"
        f"      id: '{lid}',\n"
        f"      title: '{dart_escape(title)}',\n"
        f"      field: '{dart_escape(field)}',\n"
        f"      hook: '{dart_escape(hook)}',\n"
        f"      question: '{dart_escape(ques)}',\n"
        f"      doctrine: '{dart_escape(doctrine)}',\n"
        f"      elements: <String>[{els_code}],\n"
        f"      writingType: 'Client memo',\n"
        f"      simulationCaseId: '{case_id}',\n"
        f"      objectionIndex: {idx % 4},\n"
        f"    ),"
    )


def list_name(spec: str) -> str:
    parts = spec.split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:]) + "Topics"


def generate() -> str:
    lines: list[str] = [
        "import '../../models/law/law_program.dart';",
        "import 'law_topic_factory.dart';",
        "",
        "/// Comprehensive standard curricula for every Law School specialization.",
        "/// IDs are prefixed with `world_` so merges with catalog/extras/core stay unique.",
        "class LawTopicWorld {",
        "  LawTopicWorld._();",
        "",
        "  static List<LawLesson> forSpec(String specId) => switch (specId) {",
    ]

    for spec in SPECS:
        lines.append(f"        '{spec}' => {list_name(spec)},")
    lines.append("        _ => const <LawLesson>[],")
    lines.append("      };")
    lines.append("")

    for spec, (field, case_id, items) in SPECS.items():
        lines.append(f"  static final List<LawLesson> {list_name(spec)} = <LawLesson>[")
        for i, item in enumerate(items):
            lines.append(lesson_call(spec, field, case_id, item, i))
        lines.append("  ];")
        lines.append("")

    lines.append("}")
    lines.append("")
    return "\n".join(lines)


